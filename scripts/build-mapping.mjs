#!/usr/bin/env node
/**
 * Generates the master topic database and cross-exam mapping from the built syllabus
 * (dist/syllabus.json) + data/mapping/config.json + data/mapping/overrides.json.
 *
 *   node scripts/build-mapping.mjs           write data/mapping/master-topics.json and cross-exam-mapping.json
 *   node scripts/build-mapping.mjs --check   fail if overrides are invalid or the committed files are out of date
 *
 * The two outputs are generated: edit overrides.json (manual mapping edits) instead.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildMapping } from '../src/mapping/build.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MDIR = join(ROOT, 'data', 'mapping');
const CHECK = process.argv.includes('--check');
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));

const sylPath = join(ROOT, 'dist', 'syllabus.json');
if (!existsSync(sylPath)) { console.error('dist/syllabus.json missing: run `npm run build:data` first'); process.exit(1); }
const syllabus = read(sylPath);
const { masterTopics, crossExamMapping, errors, warnings } = buildMapping({
  exams: syllabus.exams,
  libraryTopics: syllabus.topics,
  subjects: syllabus.subjects,
  config: read(join(MDIR, 'config.json')),
  overrides: read(join(MDIR, 'overrides.json')),
  dataVersion: syllabus.meta.dataVersion,
});
for (const w of warnings) console.warn(`WARN  ${w}`);
for (const e of errors) console.error(`ERROR ${e}`);
if (errors.length) { console.error(`✖ ${errors.length} mapping error(s)`); process.exit(1); }

const header = (kind) => ({ $comment: `GENERATED by scripts/build-mapping.mjs: do not edit. Manual mapping edits go in data/mapping/overrides.json. (${kind})` });
const outputs = {
  'master-topics.json': JSON.stringify({ ...header('master topic database'), ...masterTopics }, null, 2) + '\n',
  'cross-exam-mapping.json': JSON.stringify({ ...header('cross-exam mapping'), ...crossExamMapping }, null, 2) + '\n',
};
const c = masterTopics.meta.counts;
const summary = `${c.masters} master topics · ${c.mappings} exam mappings · similarity ${JSON.stringify(c.bySimilarity)} · verification ${JSON.stringify(c.byVerification)} · sync ${JSON.stringify(c.byDefaultSyncMode)} · ${c.unmappedExamTopics} unmapped exam topics · ${crossExamMapping.review.length} flagged for review`;

if (CHECK) {
  const stale = Object.entries(outputs).filter(([f, text]) => !existsSync(join(MDIR, f)) || readFileSync(join(MDIR, f), 'utf8').replace(/\r\n/g, '\n') !== text);
  if (stale.length) { console.error(`✖ out of date: ${stale.map(([f]) => f).join(', ')}. Run \`npm run build:mapping\``); process.exit(1); }
  console.log(`✔ mapping valid and up to date: ${summary}`);
} else {
  for (const [f, text] of Object.entries(outputs)) writeFileSync(join(MDIR, f), text);
  console.log(`✔ ${summary}\n  → data/mapping/master-topics.json, data/mapping/cross-exam-mapping.json`);
}
